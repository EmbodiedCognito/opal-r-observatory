import { analyses } from '../domain/catalog';
import { proposalFor } from '../domain/recommend';
import { datasetToR } from '../runtime/rCode';
import { filename, type ProjectBundle } from './bundle';

// Never export executable commands supplied by an imported project.
export function exportRScript(project: ProjectBundle, analysisId: string) {
  const recorded = project.analyses.find(item => item.id === analysisId);
  if (!recorded) throw new Error('The recorded analysis is missing.');
  const source = project.snapshots.find(item => item.id === recorded.snapshotId);
  if (!source) throw new Error('The original data snapshot is missing.');
  const method = analyses.find(item => item.id === recorded.analysisId);
  if (!method) throw new Error('This analysis method cannot be regenerated by this version of Opal.');
  const plan = proposalFor(method, source.dataset, recorded.mapping);
  const comment = (text: string) => text.split(/\r\n|\r|\n|\u2028|\u2029/).map(line => `# ${line}`).join('\n');
  return {
    filename: filename(`${project.name}-${method.id}`).replace(/\.opal$/, '.R'),
    content: [
      '# Opal: rerun a saved analysis in base R',
      '# Review this file before running it. It contains original data rows; keep it private.',
      '# Commands are freshly generated from the saved method, mapping and source snapshot.',
      '# This is not an exact copy of historical code or verification of the recorded result.',
      comment(`Project: ${project.name}`), comment(`Source: ${source.dataset.name}`),
      comment(`Method: ${method.name}`), comment(`Recorded outcome: ${recorded.outcome}`),
      comment(`Recorded runtime: ${recorded.runtime ?? 'not recorded'}`),
      '# The current dataset and attached model conversations are not included.',
      '', datasetToR(source.dataset), '', plan.rCode, '',
    ].join('\n'),
  };
}
